/**
 * 批量從 NameGain 電子名片抓取自我介紹，寫入 bni_members.bio
 *
 *   node scripts/seed-bios-from-cards.mjs
 *   node scripts/seed-bios-from-cards.mjs --dry-run
 *   node scripts/seed-bios-from-cards.mjs --limit 10
 */
import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';
import { rawSql } from './insforge-admin-api.mjs';
import { fetchBioFromCardUrl } from './namegain-bio.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const dryRun = process.argv.includes('--dry-run');
const exportSql = process.argv.includes('--export-sql');
const limitArg = process.argv.find((a, i) => process.argv[i - 1] === '--limit');
const limit = limitArg ? parseInt(limitArg, 10) : 0;

function sqlEscape(s) {
  return String(s || '').replace(/'/g, "''");
}

function loadCardLinks() {
  const js = readFileSync(join(__dirname, '../src/data/cardLinks.js'), 'utf8');
  const m = js.match(/const E = \{([\s\S]*?)\};/);
  if (!m) throw new Error('cardLinks E block not found');
  const links = {};
  const re = /['"]([^'"]+)['"]\s*:\s*['"]([^'"]+)['"]/g;
  let match;
  while ((match = re.exec(m[1])) !== null) {
    links[match[1]] = `https://namegain.introvista.ai/card/${match[2]}`;
  }
  return links;
}

function cjkName(s) {
  return String(s || '').replace(/[^㐀-鿿]/g, '');
}

function sleep(ms) {
  return new Promise(r => setTimeout(r, ms));
}

async function main() {
  if (!process.env.BNI_API_KEY && !dryRun) {
    console.error('Set BNI_API_KEY (or use --dry-run)');
    process.exit(1);
  }

  const cardLinks = loadCardLinks();
  let todo;

  if (dryRun && !process.env.BNI_API_KEY) {
    todo = Object.entries(cardLinks).map(([nameKey, url]) => ({
      id: null, name: nameKey, bio: '', url, nameKey,
    }));
    if (limit > 0) todo = todo.slice(0, limit);
  } else {
    const { rows } = await rawSql(
      'SELECT id, name, branch, bio, card_link FROM bni_members WHERE active = true ORDER BY roster_id NULLS LAST, name'
    );
    todo = (rows || []).map(row => {
      const nameKey = cjkName(row.name);
      const url = row.card_link || cardLinks[nameKey] || '';
      return { ...row, url, nameKey };
    }).filter(r => r.url);
    if (limit > 0) todo = todo.slice(0, limit);
  }

  console.log(`Fetching bios for ${todo.length} members (${Object.keys(cardLinks).length} card links in map)…`);
  let ok = 0;
  let skip = 0;
  let fail = 0;
  const sqlLines = ['-- Auto-generated by seed-bios-from-cards.mjs', `-- ${new Date().toISOString()}`, ''];

  for (const row of todo) {
    try {
      const bio = await fetchBioFromCardUrl(row.url);
      if (row.bio?.trim() === bio.trim()) {
        console.log(`  = ${row.name} (unchanged)`);
        skip++;
      } else if (dryRun || !row.id) {
        console.log(`  ✓ ${row.name}\n    ${bio.slice(0, 120)}${bio.length > 120 ? '…' : ''}`);
        ok++;
        if (exportSql) {
          const nameKey = row.name || row.nameKey;
          sqlLines.push(
            `UPDATE bni_members SET bio = '${sqlEscape(bio)}', card_link = COALESCE(NULLIF(card_link,''), '${sqlEscape(row.url)}'), updated_at = now() WHERE active = true AND regexp_replace(name, '[^\\u4e00-\\u9fff]', '', 'g') = '${sqlEscape(cjkName(nameKey))}';`
          );
        }
      } else {
        const escBio = bio.replace(/'/g, "''");
        const escUrl = row.url.replace(/'/g, "''");
        await rawSql(
          `UPDATE bni_members SET bio = '${escBio}', card_link = COALESCE(NULLIF(card_link,''), '${escUrl}'), updated_at = now() WHERE id = '${row.id}'`
        );
        console.log(`  ✓ ${row.name} (${bio.length} chars)`);
        ok++;
      }
      await sleep(400);
    } catch (e) {
      console.log(`  ✗ ${row.name}: ${e.message}`);
      fail++;
    }
  }

  if (exportSql && sqlLines.length > 3) {
    const outPath = join(__dirname, 'seed-bios-from-cards-output.sql');
    writeFileSync(outPath, sqlLines.join('\n') + '\n', 'utf8');
    console.log(`\nWrote ${ok} UPDATE statements → ${outPath}`);
  }

  console.log(`\nDone: ${ok} updated, ${skip} unchanged, ${fail} failed${dryRun ? ' (dry-run)' : ''}.`);
}

main().catch(e => { console.error(e); process.exit(1); });
